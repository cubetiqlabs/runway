#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-${ROOT_DIR}/.env}"
BACKUP_DIR_DEFAULT="${BACKUP_DIR:-${ROOT_DIR}/backups}"
LOCK_DIR="/tmp/runway-deploy.lock"
COMPOSE_BASE="${ROOT_DIR}/docker-compose.yml"
COMPOSE_PROD="${ROOT_DIR}/docker-compose.prod.yml"
COMPOSE_DOCKER="${ROOT_DIR}/docker-compose.docker.yml"
DOCKER_OVERLAY_ENABLED="${DOCKER_OVERLAY_ENABLED:-false}"

export DOCKER_BUILDKIT=1
export COMPOSE_DOCKER_CLI_BUILD=1

log()  { printf '[%s] [INFO] %s\n'  "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*"; }
warn() { printf '[%s] [WARN] %s\n'  "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*" >&2; }
err()  { printf '[%s] [ERROR] %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$*" >&2; exit 1; }

acquire_lock() {
  if ! mkdir "${LOCK_DIR}" 2>/dev/null; then
    err "Another deployment or backup operation is already running (lock: ${LOCK_DIR})."
  fi
  trap 'rmdir "${LOCK_DIR}" 2>/dev/null || true' EXIT
}

gen_hex() {
  local bytes="${1:-32}"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "${bytes}"
  else
    head -c "${bytes}" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

gen_base64() {
  local bytes="${1:-32}"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 "${bytes}" | tr -d '\n'
  else
    head -c "${bytes}" /dev/urandom | base64 | tr -d '\n'
  fi
}

should_enable_docker_overlay() {
  if [[ "${DOCKER_OVERLAY_ENABLED}" == "true" ]]; then
    return 0
  fi
  if [[ "${RUNWAY_ORCHESTRATOR_PROVIDER:-}" == "docker" ]]; then
    local sock="${RUNWAY_ORCHESTRATOR_DOCKER_SOCKET:-}"
    if [[ -z "${sock}" || "${sock}" == "/var/run/docker.sock" || "${sock}" == "tcp://docker-proxy:2375" ]]; then
      return 0
    fi
  fi
  return 1
}

compose_cmd() {
  local prod_mode="${1:-false}"
  shift
  local files=(-f "${COMPOSE_BASE}")
  if [[ "${prod_mode}" == "true" ]]; then
    files+=(-f "${COMPOSE_PROD}")
  fi
  if should_enable_docker_overlay && [[ -f "${COMPOSE_DOCKER}" ]]; then
    files+=(-f "${COMPOSE_DOCKER}")
  fi
  docker compose --env-file "${ENV_FILE}" "${files[@]}" "$@"
}

load_env() {
  [[ -f "${ENV_FILE}" ]] || err "Env file not found at ${ENV_FILE}. Run './scripts/deploy.sh init' first."
  set -a
  # shellcheck disable=SC1090
  source "${ENV_FILE}"
  set +a
}

validate_prod_secrets() {
  local pg_pass="${POSTGRES_PASSWORD:-}"
  local sess="${RUNWAY_SECURITY_SESSION_SECRET:-}"
  local enc="${RUNWAY_SECURITY_ENCRYPTION_KEY:-}"
  local admin_pw="${RUNWAY_ADMIN_PASSWORD:-}"

  if [[ -z "${pg_pass}" || "${pg_pass}" == "runway_dev_password" ]]; then
    err "Unsafe POSTGRES_PASSWORD for production. Re-run './scripts/deploy.sh init --force' or update ${ENV_FILE}."
  fi
  if [[ ${#sess} -lt 32 || "${sess}" == *"change-me"* ]]; then
    err "RUNWAY_SECURITY_SESSION_SECRET must be >= 32 random chars for production."
  fi
  if [[ ${#enc} -lt 32 || "${enc}" == *"change-me"* ]]; then
    err "RUNWAY_SECURITY_ENCRYPTION_KEY must be >= 32 bytes/chars for production."
  fi
  if [[ -z "${admin_pw}" || "${admin_pw}" == "RunwayAdmin123!" ]]; then
    warn "RUNWAY_ADMIN_PASSWORD is empty or default; change it after first bootstrap."
  fi
}

sha256_file() {
  local file="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "${file}"
  else
    shasum -a 256 "${file}"
  fi
}

verify_sha256() {
  local sum_file="$1"
  local dir
  dir="$(dirname "${sum_file}")"
  if command -v sha256sum >/dev/null 2>&1; then
    (cd "${dir}" && sha256sum -c "$(basename "${sum_file}")")
  else
    (cd "${dir}" && shasum -a 256 -c "$(basename "${sum_file}")")
  fi
}

cmd_init() {
  local force="false"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --force) force="true"; shift ;;
      *) err "Unknown option for init: $1" ;;
    esac
  done

  if [[ -f "${ENV_FILE}" && "${force}" != "true" ]]; then
    err "${ENV_FILE} already exists. Use '--force' to overwrite (a timestamped backup will be saved)."
  fi
  if [[ -f "${ENV_FILE}" ]]; then
    local prev_backup="${ENV_FILE}.bak.$(date +%Y%m%d%H%M%S)"
    cp "${ENV_FILE}" "${prev_backup}"
    chmod 600 "${prev_backup}"
    log "Backed up previous env file to ${prev_backup}"
  fi

  local pg_pass sess_secret enc_key wh_secret admin_pass docker_gid
  pg_pass="$(gen_hex 24)"
  sess_secret="$(gen_base64 36)"
  enc_key="$(gen_base64 32)"
  wh_secret="$(gen_hex 32)"
  admin_pass="$(gen_base64 18)"
  docker_gid="999"
  if [[ -S /var/run/docker.sock ]]; then
    if stat -c '%g' /var/run/docker.sock >/dev/null 2>&1; then
      docker_gid="$(stat -c '%g' /var/run/docker.sock)"
    elif stat -f '%g' /var/run/docker.sock >/dev/null 2>&1; then
      docker_gid="$(stat -f '%g' /var/run/docker.sock)"
    fi
  fi

  mkdir -p "$(dirname "${ENV_FILE}")" "${BACKUP_DIR_DEFAULT}"
  umask 077
  cat >"${ENV_FILE}" <<EOF
# Generated by scripts/deploy.sh init on $(date -u '+%Y-%m-%dT%H:%M:%SZ')
POSTGRES_USER=runway
POSTGRES_PASSWORD=${pg_pass}
POSTGRES_DB=runway
POSTGRES_PORT=5432

RUNWAY_IMAGE=ghcr.io/cubetiqlabs/runway:latest
RUNWAY_VERSION=1.0.0
RUNWAY_APP_ENVIRONMENT=production
APP_PORT=8080

RUNWAY_SECURITY_SESSION_SECRET=${sess_secret}
RUNWAY_SECURITY_ENCRYPTION_KEY=${enc_key}
RUNWAY_SECURITY_COOKIE_SECURE=true
RUNWAY_SECURITY_COOKIE_SAME_SITE=Strict

RUNWAY_ADMIN_EMAIL=admin@runway.local
RUNWAY_ADMIN_PASSWORD=${admin_pass}

# Configure your GitHub App credentials below:
RUNWAY_GITHUB_APP_ID=0
RUNWAY_GITHUB_APP_SLUG=runway
RUNWAY_GITHUB_WEBHOOK_SECRET=${wh_secret}
RUNWAY_GITHUB_PRIVATE_KEY_PEM=

RUNWAY_ORCHESTRATOR_PROVIDER=simulated
RUNWAY_ORCHESTRATOR_DOCKER_SOCKET=tcp://docker-proxy:2375
RUNWAY_ORCHESTRATOR_DEFAULT_IMAGE=ghcr.io/actions/actions-runner:latest
RUNWAY_LOGGING_LEVEL=info
RUNWAY_LOGGING_FORMAT=json
BACKUP_RETENTION_DAYS=14
EOF
  chmod 600 "${ENV_FILE}"

  log "Initialized production environment at ${ENV_FILE} (mode 600)."
  printf '\nBootstrap Credentials (save securely):\n'
  printf '  Admin Email:     admin@runway.local\n'
  printf '  Admin Password:  %s\n' "${admin_pass}"
  printf '  Webhook Secret:  %s\n\n' "${wh_secret}"
  printf 'Next steps:\n'
  printf '  1. Set RUNWAY_GITHUB_APP_ID and RUNWAY_GITHUB_PRIVATE_KEY_PEM in %s\n' "${ENV_FILE}"
  printf '  2. Deploy: ./scripts/deploy.sh deploy --mode pull --prod\n'
}

cmd_backup() {
  load_env
  local out_dir="${1:-${BACKUP_DIR_DEFAULT}}"
  local retention="${BACKUP_RETENTION_DAYS:-14}"
  mkdir -p "${out_dir}"

  local pg_id
  pg_id="$(compose_cmd false ps -q postgres || true)"
  [[ -n "${pg_id}" ]] || err "Postgres container is not running. Start it before running backup."

  local ts dump_file
  ts="$(date -u '+%Y%m%dT%H%M%SZ')"
  dump_file="${out_dir}/runway_${ts}.dump"

  log "Creating compressed PostgreSQL 18 backup at ${dump_file}..."
  compose_cmd false exec -T postgres pg_dump \
    -U "${POSTGRES_USER:-runway}" \
    -d "${POSTGRES_DB:-runway}" \
    --format=custom \
    --compress=9 \
    --no-owner \
    --no-privileges > "${dump_file}"

  [[ -s "${dump_file}" ]] || { rm -f "${dump_file}"; err "Backup produced an empty file."; }

  (cd "${out_dir}" && sha256_file "$(basename "${dump_file}")" > "$(basename "${dump_file}").sha256")
  chmod 600 "${dump_file}" "${dump_file}.sha256"

  if [[ "${retention}" =~ ^[0-9]+$ ]] && [[ "${retention}" -gt 0 ]]; then
    find "${out_dir}" -type f \( -name 'runway_*.dump' -o -name 'runway_*.dump.sha256' \) -mtime +"${retention}" -delete || true
  fi

  log "Backup complete: ${dump_file} ($(du -h "${dump_file}" | awk '{print $1}'))"
}

cmd_restore() {
  load_env
  local dump_file="${1:-}"
  shift || true
  [[ -n "${dump_file}" && -f "${dump_file}" ]] || err "Usage: ./scripts/deploy.sh restore <backup_file.dump> [--yes]"

  local assume_yes="false"
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --yes|-y) assume_yes="true"; shift ;;
      *) err "Unknown option for restore: $1" ;;
    esac
  done

  if [[ -f "${dump_file}.sha256" ]]; then
    log "Verifying SHA-256 checksum for ${dump_file}..."
    verify_sha256 "${dump_file}.sha256"
  else
    warn "Checksum file ${dump_file}.sha256 not found; skipping checksum verification."
  fi

  if [[ "${assume_yes}" != "true" ]]; then
    printf 'WARNING: This will overwrite database "%s". Continue? [y/N]: ' "${POSTGRES_DB:-runway}"
    read -r reply
    [[ "${reply}" =~ ^[Yy]$ ]] || err "Restore aborted by user."
  fi

  local pg_id
  pg_id="$(compose_cmd false ps -q postgres || true)"
  if [[ -z "${pg_id}" ]]; then
    log "Starting PostgreSQL container..."
    compose_cmd false up -d --wait postgres
  fi

  if [[ "${SKIP_PRE_RESTORE_BACKUP:-false}" != "true" ]]; then
    log "Taking pre-restore safety backup..."
    cmd_backup "${BACKUP_DIR_DEFAULT}" || warn "Pre-restore safety backup skipped (empty or fresh DB)."
  fi

  local was_app_running="false"
  if [[ -n "$(compose_cmd false ps -q runway 2>/dev/null || true)" ]]; then
    was_app_running="true"
  fi

  log "Stopping runway application container during restore..."
  compose_cmd false stop runway >/dev/null 2>&1 || true

  log "Restoring PostgreSQL 18 backup from ${dump_file}..."
  compose_cmd false exec -T postgres pg_restore \
    -U "${POSTGRES_USER:-runway}" \
    -d "${POSTGRES_DB:-runway}" \
    --clean \
    --if-exists \
    --no-owner \
    --no-privileges \
    --single-transaction < "${dump_file}"

  if [[ "${was_app_running}" == "true" ]]; then
    log "Restarting runway..."
    compose_cmd false up -d --no-build --wait runway
  fi
  log "Restore completed successfully."
}

cmd_deploy() {
  acquire_lock
  load_env

  local mode="pull"
  local branch="main"
  local prod_mode="false"
  local skip_backup="false"

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --mode) mode="${2:-}"; shift 2 ;;
      --branch) branch="${2:-}"; shift 2 ;;
      --prod) prod_mode="true"; shift ;;
      --docker) DOCKER_OVERLAY_ENABLED="true"; shift ;;
      --skip-backup) skip_backup="true"; shift ;;
      *) err "Unknown option for deploy: $1" ;;
    esac
  done

  if [[ "${prod_mode}" == "true" ]]; then
    validate_prod_secrets
  fi

  if [[ "${skip_backup}" != "true" ]]; then
    local pg_id
    pg_id="$(compose_cmd "${prod_mode}" ps -q postgres 2>/dev/null || true)"
    if [[ -n "${pg_id}" ]]; then
      cmd_backup "${BACKUP_DIR_DEFAULT}" || warn "Pre-deploy backup failed; continuing because --skip-backup was not forced."
    fi
  fi

  if git -C "${ROOT_DIR}" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    if git -C "${ROOT_DIR}" remote get-url origin >/dev/null 2>&1; then
      log "Pulling latest source from origin/${branch}..."
      git -C "${ROOT_DIR}" fetch --quiet origin "${branch}"
      git -C "${ROOT_DIR}" pull --ff-only origin "${branch}"
    else
      log "No git remote 'origin' configured; skipping git pull."
    fi
  fi

  case "${mode}" in
    pull)
      log "Pulling image ${RUNWAY_IMAGE:-ghcr.io/cubetiqlabs/runway:latest}..."
      compose_cmd "${prod_mode}" pull runway
      compose_cmd "${prod_mode}" up -d --remove-orphans --wait
      ;;
    build)
      log "Building Runway with BuildKit..."
      compose_cmd "${prod_mode}" build
      compose_cmd "${prod_mode}" up -d --remove-orphans --wait
      ;;
    *)
      err "Invalid --mode '${mode}'. Expected 'build' or 'pull'."
      ;;
  esac

  local port="${APP_PORT:-8080}"
  if command -v curl >/dev/null 2>&1 && [[ -n "${port}" ]]; then
    if curl -sf "http://127.0.0.1:${port}/healthz" >/dev/null && curl -sf "http://127.0.0.1:${port}/readyz" >/dev/null; then
      log "Health and readiness probes passed on 127.0.0.1:${port}."
    fi
  fi

  docker image prune -f >/dev/null 2>&1 || true
  log "Deployment complete."
}

cmd_auto_deploy() {
  load_env
  local mode="pull"
  local branch="main"
  local prod_mode="false"
  local args=("$@")

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --mode) mode="${2:-}"; shift 2 ;;
      --branch) branch="${2:-}"; shift 2 ;;
      --prod) prod_mode="true"; shift ;;
      --docker) DOCKER_OVERLAY_ENABLED="true"; shift ;;
      *) shift ;;
    esac
  done

  if [[ "${mode}" == "build" ]]; then
    if git -C "${ROOT_DIR}" rev-parse --is-inside-work-tree >/dev/null 2>&1 && git -C "${ROOT_DIR}" remote get-url origin >/dev/null 2>&1; then
      git -C "${ROOT_DIR}" fetch --quiet origin "${branch}"
      local local_sha remote_sha
      local_sha="$(git -C "${ROOT_DIR}" rev-parse HEAD)"
      remote_sha="$(git -C "${ROOT_DIR}" rev-parse "origin/${branch}")"
      if [[ "${local_sha}" == "${remote_sha}" ]]; then
        log "Already up to date (${local_sha:0:8}); skipping deploy."
        return 0
      fi
      log "New commit detected (${local_sha:0:8} -> ${remote_sha:0:8}); deploying..."
    fi
  else
    local before_id after_id img
    img="${RUNWAY_IMAGE:-ghcr.io/cubetiqlabs/runway:latest}"
    before_id="$(docker image inspect -f '{{.Id}}' "${img}" 2>/dev/null || echo 'none')"
    compose_cmd "${prod_mode}" pull -q runway
    after_id="$(docker image inspect -f '{{.Id}}' "${img}" 2>/dev/null || echo 'none')"
    if [[ "${before_id}" == "${after_id}" && "${before_id}" != "none" ]]; then
      log "Container image unchanged (${before_id:0:19}); skipping deploy."
      return 0
    fi
    log "New container image detected; deploying..."
  fi

  cmd_deploy "${args[@]}"
}

cmd_install_cron() {
  local interval="*/5 * * * *"
  local backup_schedule="0 3 * * *"
  local mode="pull"
  local prod_flag=""
  local docker_flag=""

  while [[ $# -gt 0 ]]; do
    case "$1" in
      --interval) interval="${2:-}"; shift 2 ;;
      --backup-schedule) backup_schedule="${2:-}"; shift 2 ;;
      --mode) mode="${2:-}"; shift 2 ;;
      --prod) prod_flag="--prod"; shift ;;
      --docker) docker_flag="--docker"; shift ;;
      *) err "Unknown option for install-cron: $1" ;;
    esac
  done

  local log_dir="${ROOT_DIR}/logs"
  mkdir -p "${log_dir}"
  local marker="# runway-managed"
  local deploy_line="${interval} cd ${ROOT_DIR} && ./scripts/deploy.sh auto-deploy --mode ${mode} ${prod_flag} ${docker_flag} >> ${log_dir}/deploy.log 2>&1 ${marker}"
  local backup_line="${backup_schedule} cd ${ROOT_DIR} && ./scripts/deploy.sh backup >> ${log_dir}/backup.log 2>&1 ${marker}"

  local current filtered
  current="$(crontab -l 2>/dev/null || true)"
  filtered="$(printf '%s\n' "${current}" | grep -v "${marker}" || true)"

  printf '%s\n%s\n%s\n' "${filtered}" "${deploy_line}" "${backup_line}" | sed '/^$/N;/^\n$/D' | crontab -
  log "Installed auto-deploy and nightly backup cron jobs."
}

cmd_status() {
  load_env
  compose_cmd false ps
}

cmd_logs() {
  load_env
  local svc="${1:-runway}"
  compose_cmd false logs -f --tail=100 "${svc}"
}

cmd_help() {
  cat <<'EOF'
Runway Production Deployment CLI

Usage:
  ./scripts/deploy.sh <command> [options]

Commands:
  init [--force]
      Generate production .env (mode 600) with cryptographic secrets and create backups/.

  deploy [--mode pull|build] [--branch main] [--prod] [--skip-backup]
      Take pre-deploy DB backup (if running), git pull (if remote exists), pull/build,
      start services with --wait, verify /healthz & /readyz, and prune old images.

  auto-deploy [--mode pull|build] [--branch main] [--prod]
      Check for new container image digests or git commits and deploy only if changed.

  install-cron [--interval "*/5 * * * *"] [--backup-schedule "0 3 * * *"] [--mode pull|build] [--prod]
      Install crontab entries for automatic pull/deploy and daily PostgreSQL backups.

  backup [backup_dir]
      Create compressed PostgreSQL 18 custom dump + .sha256 and enforce retention pruning.

  restore <backup_file.dump> [--yes]
      Verify checksum, take safety backup, stop app, pg_restore atomically, and restart app.

  status              Show docker compose service status.
  logs [service]      Tail docker compose logs (default: runway).
  help                Show this help text.
EOF
}

CMD="${1:-help}"
shift || true

case "${CMD}" in
  init)         cmd_init "$@" ;;
  deploy)       cmd_deploy "$@" ;;
  auto-deploy)  cmd_auto_deploy "$@" ;;
  install-cron) cmd_install_cron "$@" ;;
  backup)       cmd_backup "$@" ;;
  restore)      cmd_restore "$@" ;;
  status)       cmd_status "$@" ;;
  logs)         cmd_logs "$@" ;;
  help|-h|--help) cmd_help ;;
  *)            err "Unknown command '${CMD}'. Run './scripts/deploy.sh help'." ;;
esac
